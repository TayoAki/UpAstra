// Measures how wide each printable ASCII character renders in libass, for
// every bundled font, and writes server/font-metrics.ts. Overlays use it to
// fit text to its box. Run: node scripts/measure-fonts.mjs (needs ffmpeg).
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const FONTS = ["Poppins Black", "Poppins ExtraBold", "Poppins Bold", "Anton", "Bebas Neue", "Archivo Black"];
const CHARS = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i));
const REP = 20, FS = 100, ROW = 160, W = 4000, H = ROW * CHARS.length;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "fm-"));
const fontsDir = path.resolve("fonts");
const out = {};
for (const font of FONTS) {
  // Each row: the character repeated REP times between two bars, so leading
  // and trailing spaces count too. Width = (bar gap − the bars' own gap) / REP.
  const ev = CHARS.map((c, i) => {
    const t = c === "\\" ? "\\\\" : c === "{" || c === "}" ? c : c;
    return `Dialogue: 0,0:00:00.00,0:00:01.00,M,,0,0,0,,{\\an4\\pos(10,${i * ROW + ROW / 2})}|${(c === "{" ? "\\{" : t).repeat(REP)}|`;
  });
  const base = `Dialogue: 0,0:00:00.00,0:00:01.00,M,,0,0,0,,{\\an4\\pos(10,${H - ROW / 2})}||`;
  const ass = ["[Script Info]", "ScriptType: v4.00+", `PlayResX: ${W}`, `PlayResY: ${H}`, "WrapStyle: 2", "", "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    `Style: M,${font},${FS},&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,4,0,0,0,1`, "", "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text", ...ev.slice(0, -1), base, ""].join("\n");
  // The last row is replaced by the bare "||" reference (row 94 is "~", measured separately below).
  const file = path.join(dir, "m.ass");
  fs.writeFileSync(file, ass);
  const raw = execFileSync("ffmpeg", ["-v", "error", "-f", "lavfi", "-i", `color=c=black:s=${W}x${H}:d=1`, "-frames:v", "1", "-vf", `ass=${file}:fontsdir=${fontsDir},format=gray`, "-f", "rawvideo", "-"], { maxBuffer: W * H + 1024 });
  const extent = (row) => {
    let lo = -1, hi = -1;
    for (let y = row * ROW; y < (row + 1) * ROW; y++)
      for (let x = 0; x < W; x++) if (raw[y * W + x] > 128) { if (lo < 0 || x < lo) lo = x; if (x > hi) hi = x; }
    return hi - lo;
  };
  const bars = extent(CHARS.length - 1);
  const widths = {};
  for (let i = 0; i < CHARS.length - 1; i++) widths[CHARS[i]] = Math.round(((extent(i) - bars) / REP / FS) * 1000) / 1000;
  widths["~"] = widths["-"];
  out[font] = widths;
  console.log(font, "M", widths.M, "a", widths.a, "space", widths[" "]);
}
// CJK falls back to a system CJK font whatever the style's font: Noto Sans
// CJK in production (Dockerfile), possibly another locally. Measure each one
// installed and keep the widest.
const cjkWidth = (cjkFont) => {
  const W2 = 3000, H2 = 200, N = 10;
  const ass = ["[Script Info]", "ScriptType: v4.00+", `PlayResX: ${W2}`, `PlayResY: ${H2 * 2}`, "WrapStyle: 2", "", "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    `Style: M,${cjkFont},${FS},&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,4,0,0,0,1`, "", "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    `Dialogue: 0,0:00:00.00,0:00:01.00,M,,0,0,0,,{\\an4\\pos(10,100)}|${"中".repeat(N)}|`,
    `Dialogue: 0,0:00:00.00,0:00:01.00,M,,0,0,0,,{\\an4\\pos(10,300)}||`, ""].join("\n");
  const file = path.join(dir, "c.ass");
  fs.writeFileSync(file, ass);
  const raw = execFileSync("ffmpeg", ["-v", "error", "-f", "lavfi", "-i", `color=c=black:s=${W2}x${H2 * 2}:d=1`, "-frames:v", "1", "-vf", `ass=${file}:fontsdir=${fontsDir},format=gray`, "-f", "rawvideo", "-"], { maxBuffer: W2 * H2 * 2 + 1024 });
  const ext = (y0) => { let lo = -1, hi = -1; for (let y = y0; y < y0 + H2; y++) for (let x = 0; x < W2; x++) if (raw[y * W2 + x] > 128) { if (lo < 0 || x < lo) lo = x; if (x > hi) hi = x; } return hi - lo; };
  return Math.round(((ext(0) - ext(H2)) / N / FS) * 1000) / 1000;
};
const installed = (f) => execFileSync("fc-list", [":", "family"], { encoding: "utf8" }).includes(f);
const cjkFonts = ["Noto Sans CJK JP", "Noto Sans CJK SC", "WenQuanYi Zen Hei"].filter(installed);
const cjk = Math.max(...cjkFonts.map((f) => { const w = cjkWidth(f); console.log("CJK", f, w); return w; }));
const body = `// Generated by scripts/measure-fonts.mjs — libass advance widths per character,\n// as a fraction of the ASS font size, for the bundled fonts.\nexport const FONT_WIDTHS: Record<string, Record<string, number>> = ${JSON.stringify(out)};\n\n/** Width of a CJK character (drawn with a CJK fallback font; the widest of ${cjkFonts.join(", ")}), as a fraction of the font size. */\nexport const WIDE_EM = ${cjk};\n`;
fs.writeFileSync("server/font-metrics.ts", body);
fs.rmSync(dir, { recursive: true, force: true });
